// messages: [{role:"user"|"assistant", content}]；opt: { a: 客户钱包, ctxLines: 链上情况, style: 额外风格要求 }
export async function answer(env, messages, opt = {}) {
  const a = /^0x[0-9a-f]{40}$/.test(String(opt.a || "")) ? String(opt.a) : "";
  const ctxLines = (Array.isArray(opt.ctxLines) ? opt.ctxLines : []).slice(0, 12).map((x) => String(x).slice(0, 200));
  const extra = (UPDATES.length ? "\n\n【最近更新（新的在前）】\n" + UPDATES.slice(0, 12).map((u) => "- " + u.d + "：" + u.t).join("\n") : "") +
    (a ? "\n\n【这位客户（钱包 " + a.slice(0, 6) + "…" + a.slice(-4) + "）的链上实时情况】\n" + (ctxLines.length ? ctxLines.map((x) => "- " + x).join("\n") : "- 现在没有挂单、借贷或预测") + "\n如果客户问「我的单 / 我的钱 / 我的借贷」，直接用上面的实时情况回答。" : "") +
    (opt.style ? "\n\n" + opt.style : "");
  const msgs = (Array.isArray(messages) ? messages : []).slice(-8)
    .filter((m) => m && (m.role === "user" || m.role === "assistant") && typeof m.content === "string")
    .map((m) => ({ role: m.role, content: m.content.slice(0, 600) }));
  if (!msgs.length || msgs[msgs.length - 1].role !== "user") return { error: "no question" };
  const turns = [];
  for (const m of msgs) { if (!turns.length && m.role !== "user") continue; if (turns.length && turns[turns.length - 1].role === m.role) turns[turns.length - 1].content += "\n" + m.content; else turns.push({ role: m.role, content: m.content }); }
  let text = "", engine = "", claudeErr = "";
  if (env.ANTHROPIC_API_KEY && turns.length) {
    try {
      const r = await fetch("https://api.anthropic.com/v1/messages", {
        method: "POST", headers: { "x-api-key": env.ANTHROPIC_API_KEY, "anthropic-version": "2023-06-01", "content-type": "application/json" },
        body: JSON.stringify({ model: env.CLAUDE_MODEL || "claude-haiku-5-5", max_tokens: 500, system: KNOWLEDGE + extra, messages: turns }),
      });
      if (r.ok) { const j = await r.json(); text = (j.content || []).map((c) => c.text || "").join("").trim(); engine = "claude"; }
      else claudeErr = r.status + " " + (await r.text()).slice(0, 200);
    } catch (e) { text = ""; claudeErr = String(e && e.message || e).slice(0, 200); }
  }
  if (!text && env.AI) {
    try { const r = await env.AI.run(MODEL, { messages: [{ role: "system", content: KNOWLEDGE + extra }, ...msgs], max_tokens: 400, temperature: 0.2 }); text = String((r && r.response) || "").trim(); engine = "llama"; } catch (e) { text = ""; }
  }
  if (!text) return { error: "ai error", claudeErr };
  const human = /\[HUMAN\]/i.test(text);
  text = text.replace(/\[HUMAN\]/gi, "").trim();
  return { answer: text, human, engine, claudeErr };
}
